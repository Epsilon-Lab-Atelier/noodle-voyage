// Regenerates src/components/worldMapGeometry.ts.
//
// The world map outline comes from Natural Earth 1:110m country boundaries
// (public domain), distributed as TopoJSON in the world-atlas package. The
// outline is simplified, projected to an equirectangular map centred on 150°E
// so Japan sits near the middle, and written out as two static SVG paths so the
// app ships no map library and makes no network request to draw the map.
//
// The packages below are only needed to regenerate the file, so they are not
// project dependencies. Install them on demand:
//
//   npm install --no-save --no-package-lock d3-geo topojson-client topojson-simplify world-atlas
//   node scripts/generate-world-map.mjs
//
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { geoEquirectangular, geoPath } from 'd3-geo';
import { feature, mesh } from 'topojson-client';
import { filter, filterAttachedWeight, presimplify, simplify, sphericalRingArea, sphericalTriangleArea } from 'topojson-simplify';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, '..');

const WIDTH = 1000;
const HEIGHT = 394;
const TOP_LATITUDE = 84;
const CENTER_LONGITUDE = 150;
// Simplification tolerance in steradians, and the smallest island kept.
const TOLERANCE = 1e-4;
const MIN_RING_AREA = 6e-6;

const scale = WIDTH / (2 * Math.PI);
const projection = geoEquirectangular()
  .rotate([-CENTER_LONGITUDE, 0])
  .scale(scale)
  .translate([WIDTH / 2, (scale * TOP_LATITUDE * Math.PI) / 180]);
const toPath = geoPath(projection).digits(1);

const source = JSON.parse(
  fs.readFileSync(path.join(root, 'node_modules/world-atlas/countries-110m.json'), 'utf8')
);
// Antarctica sits below the visible latitude band.
source.objects.countries.geometries = source.objects.countries.geometries.filter(
  (geometry) => geometry.properties?.name !== 'Antarctica'
);

const presimplified = presimplify(source, sphericalTriangleArea);
const topology = filter(
  simplify(presimplified, TOLERANCE),
  filterAttachedWeight(presimplified, MIN_RING_AREA, sphericalRingArea)
);
const countries = topology.objects.countries;

const landPath = toPath(feature(topology, countries));
const borderPath = toPath(mesh(topology, countries, (a, b) => a !== b));

const output = `// Generated by scripts/generate-world-map.mjs. Do not edit by hand.
//
// Outline: Natural Earth 1:110m country boundaries (public domain), simplified
// and projected onto an equirectangular map centred on ${CENTER_LONGITUDE}°E.

export const worldMapWidth = ${WIDTH};
export const worldMapHeight = ${HEIGHT};
export const worldMapTopLatitude = ${TOP_LATITUDE};
export const worldMapCenterLongitude = ${CENTER_LONGITUDE};
export const worldMapPixelsPerDegree = worldMapWidth / 360;

/** Shifts a longitude into the ±180° range measured from the map centre. */
export function worldMapOffsetLongitude(longitude: number): number {
  return ((((longitude - worldMapCenterLongitude) % 360) + 540) % 360) - 180;
}

export function projectWorldPoint(latitude: number, longitude: number): { x: number; y: number } {
  return {
    x: (worldMapOffsetLongitude(longitude) + 180) * worldMapPixelsPerDegree,
    y: (worldMapTopLatitude - latitude) * worldMapPixelsPerDegree
  };
}

export const worldLandPath =
  '${landPath}';

export const worldBorderPath =
  '${borderPath}';
`;

const outputPath = path.join(root, 'src/components/worldMapGeometry.ts');
fs.writeFileSync(outputPath, output);
console.log(
  `Wrote ${path.relative(root, outputPath)} (land ${landPath.length} chars, borders ${borderPath.length} chars).`
);
